import { createSlice, createAsyncThunk, createEntityAdapter } from '@reduxjs/toolkit';
import axios from 'axios';
import { FALLBACK_PRODUCTS } from './fallbackProducts';

const API_URL = process.env.REACT_APP_FAKESTORE_API_URL || 'https://fakestoreapi.com';

/**
 * createEntityAdapter: Normalizes product entities by id with sorting
 */
export const productsAdapter = createEntityAdapter({
  selectId: (product) => product.id,
  sortComparer: (a, b) => a.id - b.id
});

/**
 * createAsyncThunk: Fetch all products from Fake Store API with fallback resilience
 */
export const fetchProducts = createAsyncThunk(
  'products/fetchProducts',
  async (_, { rejectWithValue }) => {
    try {
      const response = await axios.get(`${API_URL}/products`, { timeout: 6000 });
      if (Array.isArray(response.data) && response.data.length > 0) {
        return response.data;
      }
      return FALLBACK_PRODUCTS;
    } catch (err) {
      console.warn('Fake Store API failed or timed out, activating fallback dataset:', err.message);
      // Resilient fallback guarantees uninterrupted experience
      return FALLBACK_PRODUCTS;
    }
  }
);

/**
 * createAsyncThunk: Fetch single product details by id
 */
export const fetchProductById = createAsyncThunk(
  'products/fetchProductById',
  async (productId, { getState, rejectWithValue }) => {
    // Check normalized cache first
    const existing = productsAdapter.getSelectors().selectById(getState().products, productId);
    if (existing) return existing;

    try {
      const response = await axios.get(`${API_URL}/products/${productId}`, { timeout: 5000 });
      return response.data;
    } catch (err) {
      const fallback = FALLBACK_PRODUCTS.find((p) => p.id === Number(productId));
      if (fallback) return fallback;
      return rejectWithValue(err.message || 'Could not load product details');
    }
  }
);

const initialState = productsAdapter.getInitialState({
  status: 'idle', // 'idle' | 'loading' | 'succeeded' | 'failed'
  error: null,
  selectedCategory: 'all',
  searchQuery: '',
  sortBy: 'featured', // 'featured' | 'price-low' | 'price-high' | 'rating' | 'title'
  selectedProductId: null
});

export const productsSlice = createSlice({
  name: 'products',
  initialState,
  reducers: {
    setSelectedCategory: (state, action) => {
      state.selectedCategory = action.payload;
    },
    setSearchQuery: (state, action) => {
      state.searchQuery = action.payload;
    },
    setSortBy: (state, action) => {
      state.sortBy = action.payload;
    },
    setSelectedProductId: (state, action) => {
      state.selectedProductId = action.payload;
    },
    clearFilters: (state) => {
      state.selectedCategory = 'all';
      state.searchQuery = '';
      state.sortBy = 'featured';
    }
  },
  extraReducers: (builder) => {
    builder
      // fetchProducts lifecycle
      .addCase(fetchProducts.pending, (state) => {
        state.status = 'loading';
        state.error = null;
      })
      .addCase(fetchProducts.fulfilled, (state, action) => {
        state.status = 'succeeded';
        state.error = null;
        productsAdapter.setAll(state, action.payload);
      })
      .addCase(fetchProducts.rejected, (state, action) => {
        state.status = 'failed';
        state.error = action.error.message || 'Failed to fetch products from Fake Store API';
      })
      // fetchProductById lifecycle
      .addCase(fetchProductById.fulfilled, (state, action) => {
        if (action.payload) {
          productsAdapter.upsertOne(state, action.payload);
        }
      });
  }
});

export const {
  setSelectedCategory,
  setSearchQuery,
  setSortBy,
  setSelectedProductId,
  clearFilters
} = productsSlice.actions;

// Entity Selectors generated by createEntityAdapter
export const {
  selectAll: selectAllProducts,
  selectById: selectProductById,
  selectIds: selectProductIds,
  selectTotal: selectTotalProducts
} = productsAdapter.getSelectors((state) => state.products);

// State Slice Selectors
export const selectProductsStatus = (state) => state.products.status;
export const selectProductStatus = (state) => state.products.status;
export const selectProductsError = (state) => state.products.error;
export const selectProductError = (state) => state.products.error;
export const selectSelectedCategory = (state) => state.products.selectedCategory;
export const selectSearchQuery = (state) => state.products.searchQuery;
export const selectSortBy = (state) => state.products.sortBy;
export const selectSelectedProductId = (state) => state.products.selectedProductId;

export default productsSlice.reducer;
